package com.saxonica.build

import java.io.File
import java.io.PrintStream
import java.util.Calendar

// N.B. The methods in this class are not thread safe

// This is all a bit fussier than you'd like because the data formats vary.
// In particular, if the special case mapping file maps one single character
// to another single character, we don't want to treat that as special. We
// want to merge it into the common case so that it'll be collapsed in a range.

class UnicodeCaseMapper(val version: String, val cacheDir: File) {
  companion object {
    // (0) Codepoint
    // (1) Lowercase sequence
    // (2) Titlecase sequence
    // (3) Uppercase sequence
    // (4) conditions
    val specialUC = mutableMapOf<Int,String>()
    val specialLC = mutableMapOf<Int,String>()

    // (0)  Codepoint
    // (1)  Name
    // (2)  General_Category
    // (3)  Canonical_Combining_Class
    // (4)  Bidi_Class
    // (5)  Decomposition_Type / Decomposition_Mapping
    // (6)  Numeric_Type / Numeric_Value
    // (7)
    // (8)
    // (9)  Bidi_Mirrored
    // (10) Unicode_1_Name (Obsolete as of 6.2.0)
    // (11) ISO_Comment (Obsolete as of 5.2.0)
    // (12) Simple_Uppercase_Mapping
    // (13) Simple_Lowercase_Mapping
    // (14) Simple_Titlecase_Mapping
    val unicode = mutableMapOf<Int,MutableMap<String,String>>()
    var maxUnicode = 0

    val thisYear = Calendar.getInstance().get(Calendar.YEAR).toString()
  }

  private val mapping = mutableListOf<CaseMapping>()
  private var specialCount = 0
  private var rangeCount = 0
  private var singleCount = 0

  fun makeToLower(source: File, output: PrintStream) {
    lowercaseMapping()
    outputFile(source, output)
  }

  fun makeToUpper(source: File, output: PrintStream) {
    uppercaseMapping()
    outputFile(source, output)
  }

  private fun outputFile(source: File, output: PrintStream) {
    var first = true
    source.forEachLine { input ->
      if (first) {
        output.println(input)
        output.println("// This file is generated automatically; do not edit this file!")
        first = false
      }
      var line = input.replace("@@VERSION@@", version)
          .replace("@@YEAR@@", thisYear)
          .replace("@@RANGECOUNT@@", (singleCount+rangeCount).toString())
          .replace("@@SPECIALCOUNT@@", specialCount.toString())
      output.println(line)

      if (line.contains("// START GENERATED CONTENT")) {
        for (map in mapping) {
          output.println(map.toString())
        }
      }
    }
  }

  private var first = -1
  private var last = -1
  private var diff = 0

  fun uppercaseMapping() {
    loadData()

    mapping.clear()
    specialCount = 0
    rangeCount = 0
    singleCount = 0

    for (cp in 0 .. maxUnicode) {
      if (cp in unicode) {
        mapping(cp, unicode[cp]!!["uppercase"]!!, specialUC)
      }
    }
    publishMapping()

    for (map in mapping) {
      when (map) {
        is SingleMapping -> singleCount++
        is RangeMapping -> rangeCount++
        is SpecialMapping -> specialCount++
        else -> throw RuntimeException("Unexpected mapping: ${map}")
      }
    }
  }

  fun lowercaseMapping() {
    loadData()

    mapping.clear()
    specialCount = 0
    rangeCount = 0
    singleCount = 0

    for (cp in 0 .. maxUnicode) {
      if (cp in unicode) {
        mapping(cp, unicode[cp]!!["lowercase"]!!, specialLC)
      }
    }
    publishMapping()

    for (map in mapping) {
      when (map) {
        is SingleMapping -> singleCount++
        is RangeMapping -> rangeCount++
        is SpecialMapping -> specialCount++
        else -> throw RuntimeException("Unexpected mapping: ${map}")
      }
    }
  }

  private fun mapping(codepoint: Int, mappedValue: String, special: Map<Int,String>) {
    if (special[codepoint] != null) {
      publishMapping()
      mapping.add(SpecialMapping(codepoint, special[codepoint]!!))
      return
    }

    if (mappedValue != "") {
      val udiff = mappedValue.toInt(radix = 16) - codepoint

      if (first < 0) {
        first = codepoint
        last = codepoint
        diff = udiff
        return
      }

      if (codepoint == last + 1 && diff == udiff) {
        last++
        return
      }

      publishMapping()
      first = codepoint
      last = codepoint
      diff = udiff
    }
  }
  
  private fun publishMapping() {
    if (first < 0) {
      return
    }

    if (first == last) {
      mapping.add(SingleMapping(first, diff))
    } else {
      mapping.add(RangeMapping(first, last, diff))
    }

    first = -1
    last = -1
    diff = 0
  }

  private fun loadData() {
    loadUnicode()
    loadSpecials()
  }

  private fun loadUnicode() {
    if (unicode.size > 0) {
      return
    }

    val ucdFile = File(cacheDir, "UnicodeData-${version}.txt")
    ucdFile.forEachLine { input ->
      val line = if (input.contains("#")) {
        val pos = input.indexOf("#")
        input.substring(0, pos)
      } else {
        input
      }

      if (line.contains(";")) {
        val parts = line.split(";")

        val codepoint = parts[0]
        val name = parts[1]
        val uppercase = parts[12]
        val lowercase = parts[13]

        // None of the ranges have case mappings, so we don't have to worry about
        // them. But if in some future version they do, fall over...
        if (name.contains(", First>") || name.contains(", Last>")) {
          if (uppercase != "" || lowercase != "") {
            throw RuntimeException("Ranges with case mappings are not supported.")
          }
        }

        val cp = codepoint.toInt(radix = 16)
        val entry = mutableMapOf("codepoint" to parts[0],
                                 "name" to name,
                                 "uppercase" to uppercase,
                                 "lowercase" to lowercase)
        unicode[cp] = entry
        if (cp > maxUnicode) {
          maxUnicode = cp
        }
      }
    }
    //println("Loaded ${unicode.size} lines")
  }
  
  private fun loadSpecials() {
    if (specialUC.isNotEmpty()) {
      return
    }

    val special = File(cacheDir, "SpecialCasing-${version}.txt")
    special.forEachLine { input ->
      val line = if (input.contains("#")) {
        val pos = input.indexOf("#")
        input.substring(0, pos)
      } else {
        input
      }
    
      if (line.contains(";")) {
        val parts = line.split(";")
        val codepoint = parts[0].trim().toInt(radix = 16)
        val lower = parts[1].trim()
        val upper = parts[3].trim()
        val conditional = parts[4].trim() != ""

        // We ignore conditional rules (rules for specific languages)

        if (!conditional && lower != "") {
          val chars = lower.split(" ")
          
          // If there's a single character mapping, put it in the unicode data set
          if (chars.size == 1) {
            if (chars[0].toInt(radix = 16) == codepoint) {
              // Ignore self mappings
            } else {
              if (codepoint in unicode) {
                val map = unicode[codepoint]!!
                val lowercase = map.get("lowercase")
                if (lowercase != null && lowercase != chars[0]) {
                  println("Overriding lowercase mapping for ${map["name"]!!}: ${lowercase} to ${chars[0]}")
                } else {
                  //println("Special l/c mapping for ${map["name"]!!} is the same as the normal mapping")
                }
                map.put("lowercase", chars[0])
              } else {
                unicode[codepoint] = mutableMapOf("codepoint" to parts[0].trim(),
                                                  "lowercase" to chars[0])
              }
            }
          } else {
            val sb = StringBuilder()
            for (cp in lower.split(" ")) {
              val dec = cp.toInt(radix = 16)
              if (dec > 32 && dec < 127) {
                sb.append(Char(dec))
              } else {
                sb.append("\\u").append(cp)
              }
            }
            specialLC[codepoint] = sb.toString()
            //println("${codepoint}: ${sb.toString()}")
          }
        }

        if (!conditional && upper != "") {
          val chars = upper.split(" ")

          // If there's a single character mapping, put it in the unicode data set
          if (chars.size == 1) {
            if (chars[0].toInt(radix = 16) == codepoint) {
              // Ignore self mappings
            } else {
              if (codepoint in unicode) {
                val map = unicode[codepoint]!!
                val uppercase = map.get("uppercase")
                if (uppercase != null && uppercase != chars[0]) {
                  println("Overriding uppercase mapping for ${map["name"]!!}: ${uppercase} to ${chars[0]}")
                } else {
                  //println("Special u/c mapping for ${map["name"]!!} is the same as the normal mapping")
                }
                map.put("uppercase", chars[0])
              } else {
                unicode[codepoint] = mutableMapOf("codepoint" to parts[0].trim(),
                                                  "uppercase" to chars[0])
              }
            }
          } else {
            val sb = StringBuilder()
            for (cp in upper.split(" ")) {
              val dec = cp.toInt(radix = 16)
              if (dec > 32 && dec < 127) {
                sb.append(Char(dec))
              } else {
                sb.append("\\u").append(cp)
              }
            }
            specialUC[codepoint] = sb.toString()
            //println("${codepoint}: ${sb.toString()}")
          }
        }
      }
    }

    //println("Loaded ${specialLC.keys.size} lowercase specials; ${specialUC.keys.size} uppercase specials")
  }

  abstract class CaseMapping
  class SingleMapping(val codepoint: Int, val diff: Int): CaseMapping() {
    override fun toString(): String {
      return "        single(${codepoint}, ${diff});"
    }
  }
  class RangeMapping(val first: Int, val last: Int, val diff: Int): CaseMapping() {
    override fun toString(): String {
      return "        range(${first}, ${last}, ${diff});"
    }
  }
  class SpecialMapping(val codepoint: Int, val mapping: String): CaseMapping() {
    override fun toString(): String {
      return "        special(${codepoint}, \"${mapping}\");"
    }
  }
}
