package com.saxonica.build.cpp

import org.gradle.api.Action
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.FileCollection
import org.gradle.api.file.FileSystemLocation
import org.gradle.api.file.RegularFile
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.*
import org.gradle.api.tasks.*
import java.io.File
import javax.inject.Inject

class DoxygenConfigValue
@Inject constructor(val name: String, private var providerFactory: ProviderFactory) {
    private val values = mutableListOf<Provider<Any>>()
    fun value(value: String): DoxygenConfigValue {
        values.add(providerFactory.provider { listOf(value) })
        return this
    }

    fun value(addedValues: Iterable<String>): DoxygenConfigValue {
        values.add(providerFactory.provider { addedValues })
        return this
    }

    fun value(value: RegularFileProperty): DoxygenConfigValue {
        values.add(value.map { listOf(it.asFile) })
        return this
    }

    fun value(value: DirectoryProperty): DoxygenConfigValue {
        values.add(value.map { listOf(it.asFile) })
        return this
    }

    fun value(addedValues: FileCollection): DoxygenConfigValue {
        values.add(providerFactory.provider { addedValues })
        return this
    }

    fun value(value: FileSystemLocation): DoxygenConfigValue {
        values.add(providerFactory.provider { listOf(value.asFile) })
        return this
    }

    fun value(value: Provider<*>): DoxygenConfigValue {
        values.add(value.map { listOf(it) })
        return this
    }

    fun render(): String {
        val renderedValues = values.map { stringifyProvider(it) }.flatten().map { "\"${it}\"" }.joinToString(" ")
        return "${name} = ${renderedValues}"
    }

    private fun stringifyProvider(provider: Provider<Any>): Iterable<String> {
        val rawValue =  provider.get()
        if (rawValue is Iterable<*>) {
            return rawValue.map { stringifyValue(it!!) }
        } else {
            return listOf(stringifyValue(rawValue))
        }
    }

    private fun stringifyValue(value: Any): String {
        if (value is FileSystemLocation) {
            return value.asFile.toString()
        } else {
            return value.toString()
        }
    }
}

class DoxygenConfigValues
    constructor(private val providerFactory: ProviderFactory,
                private val configValues: MutableMap<String, DoxygenConfigValue> = mutableMapOf()
    ) {

    fun add(name: String): DoxygenConfigValue {
        val configValue = DoxygenConfigValue(name, providerFactory)
        configValues[name] = configValue
        return configValue
    }

    fun toList(): List<DoxygenConfigValue> {
        return configValues.values.toList()
    }
}

abstract class DoxygenTask : DefaultTask() {
    @get:InputFile
    abstract val doxyfile: RegularFileProperty
    @get:InputDirectory
    abstract val mainSrcDir: DirectoryProperty
    @get:InputDirectory
    abstract val editionSrcDir: DirectoryProperty
    @get:InputDirectory
    abstract val docSrcDir: DirectoryProperty
    @get:InputFile
    abstract val logo: RegularFileProperty
    @get:Input
    abstract val version: Property<String>
    @get:Internal
    abstract val outputDir: DirectoryProperty

    @Internal
    val configValues = DoxygenConfigValues(project.providers)

    fun configValues(action: Action<DoxygenConfigValues>) {
        action.execute(configValues)
    }

    @get:OutputDirectory
    val destinationDir = outputDir.map { it }

    @TaskAction
    fun document() {
        val renderedConfigValues = listOf<String>("").plus(configValues.toList().map { it.render() }).plus("").joinToString("\n")

        project.copy {
            into(project.layout.buildDirectory)
            from(doxyfile)
            filter { line ->
                if (line == "# Autogenerated, do not edit" ) {
                    "# Autogenerated, do not edit${renderedConfigValues}"
                } else {
                    line
                }
            }
        }

        project.exec {
            workingDir(project.layout.buildDirectory)
            commandLine("doxygen", project.layout.buildDirectory.file("Doxyfile").get().asFile)
        }
    }
}
