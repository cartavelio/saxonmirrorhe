package com.saxonica.ee.bytecode.util;

import com.saxonica.expr.JavaExtensionFunctionCall;
import net.sf.saxon.expr.CardinalityChecker;
import net.sf.saxon.expr.XPathContext;
import net.sf.saxon.expr.parser.Loc;
import net.sf.saxon.expr.parser.RoleDiagnostic;
import net.sf.saxon.lib.NamespaceConstant;
import net.sf.saxon.om.SequenceIterator;
import net.sf.saxon.om.StructuredQName;
import net.sf.saxon.s9api.Location;
import net.sf.saxon.str.UnicodeString;
import net.sf.saxon.trans.XPathException;
import net.sf.saxon.type.JavaExternalObjectType;
import net.sf.saxon.type.StringToDouble;
import net.sf.saxon.type.Type;
import net.sf.saxon.type.ValidationFailure;
import net.sf.saxon.value.AtomicValue;
import net.sf.saxon.value.ObjectValue;
import net.sf.saxon.value.Whitespace;

import java.lang.reflect.Constructor;

/**
 * A convenient place to put static methods that will be called from generated byte code
 */
public class Callback {

    /**
     * Expand a message template containing one variable string
     * @param messageTemplate the message template in which a placeholder for the inserted
     * string is indicated by the characters "{$1}"
     * @param param0 the variable string to be inserted into the message
     * @return the expanded message
     */

    public static String makeMessageFromTemplate(String messageTemplate, Object param0) {
        return messageTemplate.replace("{$1}", param0.toString());
    }

    /**
     * Construct (but don't throw) an exception reporting that two atomic values are not comparable
     *
     * @param av0      the first atomic value
     * @param av1      the second atomic value
     * @param systemId the module containing the comparison
     * @param lineNumber the line number of the comparison within this module
     * @return the exception reporting the error
     */

    public static XPathException makeNonComparableException (
            AtomicValue av0, AtomicValue av1, String systemId, int lineNumber) {

        XPathException e2 = new XPathException("Cannot compare " + Type.displayTypeName(av0) +
                " to " + Type.displayTypeName(av1), "XPTY0004", new Loc(systemId, lineNumber, -1));
        e2.setIsTypeError(true);
        return e2;
    }

    /**
     * Construct (but do not throw) an exception reporting that the namespace prefix "xml" and the XML namespace
     * URI can only be used as a pair
     *
     * @param prefix    the prefix that was actually used
     * @param isXSLT true if this is XSLT code, false if XQuery (affects the error code produced)
     * @param systemId     the module in which the error occurred
     * @param lineNumber the line number where the error occurred
     * @return the exception reporting the error condition
     */

    @SuppressWarnings({"UnusedParameters"})
    public static XPathException makeXmlNamespaceException(String prefix, boolean isXSLT, String systemId, int lineNumber) {
        String message;
        if (prefix.equals("xml")) {
            message = "When the prefix is 'xml', the namespace URI must be " + NamespaceConstant.XML;
        } else {
            message = "When the namespace URI is " + NamespaceConstant.XML + ", the prefix must be 'xml'";
        }
        String errorCode = isXSLT ? "XTDE0835" : "XQDY0096";
        Location loc = new Loc(systemId, lineNumber, -1);
        return new XPathException(message, errorCode, loc);
    }

    /**
     * Construct (but do not throw) an exception wrapping an exception thrown by a Java extension function
     *
     * @param err  the exception thrown by the called extension function
     * @param call the extension function call in which the error occurred
     * @return the exception reporting the error condition
     */

    @SuppressWarnings({"UnusedParameters"})
    public static XPathException makeJavaInvocationException(Exception err, JavaExtensionFunctionCall call) {
        XPathException xe = new XPathException("Exception thrown by extension function {" + call.getTargetMethod().toString() + "}: " +
                err, err);
        xe.setLocation(call.getLocation());
        xe.setErrorCodeQName(JavaExternalObjectType.classNameToQName(err.getClass().getName()));
        if (call.getTargetMethod() instanceof Constructor) {
            xe.setErrorObject(new ObjectValue<>(call.getTargetClass()));
        } else {
            xe.setErrorObject(new ObjectValue<>(call.getTargetMethod()));
        }
        return xe;
    }

    /**
     * Construct an exception reporting that a sequence of more than item was found where a single item
     * was expected
     *
     * @param expression the cardinality checker that detects the error. This is re-evaluated to include
     *                   the first few items of the sequence in the error message
     * @param context    the dynamic context
     * @return the exception object that reports the error
     */

    public static XPathException makeMultipleItemsException(CardinalityChecker expression, XPathContext context) {
        String depiction;
        try {
            // re-evaluate the base expression to enable the value to be displayed in the error message
            SequenceIterator offendingSequence = expression.getBaseExpression().iterate(context);
            depiction = CardinalityChecker.depictSequenceStart(offendingSequence, 2);
        } catch (XPathException err) {
            depiction = "";
        }
        RoleDiagnostic role = expression.getRoleLocator();

        String message = "A sequence of more than one item is not allowed as the " + role.getMessage() + depiction;
        XPathException err = new XPathException(message, role.getErrorCode(), expression.getLocation());
        err.setIsTypeError(true);
        err.setXPathContext(context);
        return err;
    }

    /**
     * Construct (but do not throw) an XPath exception.
     * @param message the error message
     * @param errorCode the local part of the error code
     * @param systemId the URI of the module in which the error occurs
     * @param lineNumber the line within the module where the error occurs
     * @param isTypeError true if this is a type error
     * @return the XPath exception
     */

    public static XPathException makeXPathException (
            String message,
            String errorCode,
            String systemId,
            int lineNumber,
            boolean isTypeError) {
        XPathException err = new XPathException(message, errorCode, new Loc(systemId, lineNumber, -1));
        err.setIsTypeError(isTypeError);
        return err;
    }

    /**
     * Convert a string to a double number, returning NaN if the string is not numeric
     *
     * @param s2d    the string to double converter to be used
     * @param str    the string to be converted
     * @return the returned number
     */

    public static double stringToNumberOrNaN(StringToDouble s2d, UnicodeString str) {
        try {
            return s2d.stringToNumber(str);
        } catch (NumberFormatException err) {
            return Double.NaN;
        }
    }

    /**
     * Convert a double to a integer number, throwing an exception if value is equal to NaN or infinity
     * @param value  - The double type that is required to convert
     * @return the returned integer number
     * @throws XPathException if the supplied value is NaN or infinity
     */
    public static long doubleToIntegerOrError(double value) throws XPathException {
         if (Double.isNaN(value)) {
            ValidationFailure err = new ValidationFailure("Cannot convert double NaN to an integer");
            err.setErrorCode("FOCA0002");
            throw err.makeException();
        }
        if (Double.isInfinite(value)) {
            ValidationFailure err = new ValidationFailure("Cannot convert double INF to an integer");
            err.setErrorCode("FOCA0002");
            throw err.makeException();
        }
        return (long)value;
    }

    /**
     * Convert a string to a boolean value, using the XML Schema rules (including
     * whitespace trimming)
     *
     * @param s the input string
     * @return the relevant BooleanValue if validation succeeds; or a ValidationFailure if not.
     */

    public static int booleanFromString(UnicodeString s) {
        // implementation designed to avoid creating new objects
        s = Whitespace.trim(s);
        int len = s.length32();
        if (len == 1) {
            int c = s.codePointAt(0);
            if (c == '1') {
                return 1;
            } else if (c == '0') {
                return 0;
            }
        } else if (len == 4) {
            if (s.codePointAt(0) == 't' && s.codePointAt(1) == 'r' && s.codePointAt(2) == 'u' && s.codePointAt(3) == 'e') {
                return 1;
            }
        } else if (len == 5) {
            if (s.codePointAt(0) == 'f' && s.codePointAt(1) == 'a' && s.codePointAt(2) == 'l' && s.codePointAt(3) == 's' && s.codePointAt(4) == 'e') {
                return 0;
            }
        }
        return -1;
    }

    public static StructuredQName sqNameFromValidatedEQName(String eqName, String errorCode) throws XPathException {
        try {
            return StructuredQName.fromEQName(eqName);
        } catch (IllegalArgumentException e) {
            throw new XPathException(e.getMessage(), errorCode);
        }
    }


}

